#!/usr/bin/env python3
"""Outlines of a few music glyphs (Noto Music, SIL OFL 1.1) as src/luminaraglyphs.js: Luminara's
neon clef and notes (src/luminara.js extrudes them).

Each glyph: its contours flattened to polylines (font units / unitsPerEm: about 1 per em, y up), and
its advance; three's ShapeUtils tells outlines from holes by their winding.

  .venv-depth/bin/python -I tools/glyph-outlines.py <NotoMusic-Regular.ttf> [--out src/luminaraglyphs.js]
"""
import argparse, json, os
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen

GLYPHS = { 'clef': 0x1D11E, 'quaver': 0x266A, 'quavers': 0x266B, 'crotchet': 0x2669 }


class Flatten(BasePen):
	"""Contours as polylines (curves in `steps` segments)."""

	def __init__(self, glyphset, steps=10):
		super().__init__(glyphset)
		self.contours, self.cur, self.steps = [], None, steps

	def _moveTo(self, p):
		self.cur = [ p ]

	def _lineTo(self, p):
		self.cur.append(p)

	def _qCurveToOne(self, p1, p2):
		p0 = self.cur[-1]
		for i in range(1, self.steps + 1):
			t = i / self.steps
			self.cur.append(( ( 1 - t ) ** 2 * p0[0] + 2 * ( 1 - t ) * t * p1[0] + t * t * p2[0], ( 1 - t ) ** 2 * p0[1] + 2 * ( 1 - t ) * t * p1[1] + t * t * p2[1] ))

	def _curveToOne(self, p1, p2, p3):
		p0 = self.cur[-1]
		for i in range(1, self.steps + 1):
			t = i / self.steps; u = 1 - t
			self.cur.append(( u ** 3 * p0[0] + 3 * u * u * t * p1[0] + 3 * u * t * t * p2[0] + t ** 3 * p3[0], u ** 3 * p0[1] + 3 * u * u * t * p1[1] + 3 * u * t * t * p2[1] + t ** 3 * p3[1] ))

	def _closePath(self):
		if self.cur and len(self.cur) > 2:
			if self.cur[0] == self.cur[-1]: self.cur.pop()
			self.contours.append(self.cur)
		self.cur = None

	_endPath = _closePath


def main():
	ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
	ap.add_argument('font')
	ap.add_argument('--out', default=os.path.join(os.path.dirname(__file__), '..', 'src', 'luminaraglyphs.js'))
	a = ap.parse_args()
	f = TTFont(a.font)
	em, cmap, gs = f['head'].unitsPerEm, f.getBestCmap(), f.getGlyphSet()
	out = {}
	for name, cp in GLYPHS.items():
		g = cmap[cp]
		pen = Flatten(gs)
		gs[g].draw(pen)
		out[name] = { 'advance': round(f['hmtx'][g][0] / em, 4), 'contours': [ [ [ round(x / em, 4), round(y / em, 4) ] for x, y in c ] for c in pen.contours ] }
		print(name, len(pen.contours), 'contours', sum(len(c) for c in pen.contours), 'points')
	with open(a.out, 'w') as o:
		o.write('// Generated by tools/glyph-outlines.py (do not edit): music glyphs\' outlines from Noto Music\n'
			'// (Copyright 2022 The Noto Project Authors, https://github.com/notofonts/music; SIL Open Font\n'
			'// License 1.1). Per glyph: contours (polylines, in ems, y up) and its advance.\n')
		o.write('export const GLYPHS = ' + json.dumps(out, separators=( ',', ':' )) + ';\n')


if __name__ == '__main__':
	main()
